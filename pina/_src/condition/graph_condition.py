"""Module for the Graph Data Condition class."""

import torch
from torch_geometric.data import Data

from pina._src.condition.base_condition import BaseCondition
from pina._src.core.graph import Graph


def _is_graph(value):
    """
    Check whether a value is graph data or a list or tuple.

    Lists and tuples are accepted without checking their contents.

    :param object value: The value to check.
    :return: Whether the value is a Graph, PyG Data, list, or tuple.
    :rtype: bool
    """
    if isinstance(value, (Graph, Data)):
        return True
    return isinstance(value, (list, tuple))


class GraphCondition(BaseCondition):
    """
    Base condition for graph data stored as a list of sampled subgraphs.

    Subgraphs are generated by :meth:`store_data` and stored in ``self.data``.
    Each subgraph represents one batch, retrieved by :meth:`materialize` or
    :meth:`__getitem__`.

    Concrete subclasses implement the condition residual evaluation.
    """

    def __init__(self, graph, key="x"):
        """
        Initialization of the :class:`GraphCondition` class.

        :param Graph graph: The graph from which subgraphs are sampled.
        :param str key: The name of the graph attribute containing the feature
             data. Default is ``"x"``.
        """
        self.graph = graph
        self.key = key

    def store_data(self, **kwargs):
        """
        Sample starting nodes and store their surrounding subgraphs.

        Starting nodes are sampled uniformly with replacement, so the same
        node may be selected more than once. Existing stored batches are
        replaced.

        :param dict kwargs: Sampling settings. ``n_subgraphs`` is the number
            of subgraphs to generate (int, default ``10``), and ``num_hops``
            is the number of hops around each starting node (int, default
            ``5``). Other keyword arguments are ignored.
        :return: The generated subgraphs, also stored in ``self.data``.
        :rtype: list[Graph]
        """
        n_subgraphs = kwargs.get("n_subgraphs", 10)
        num_hops = kwargs.get("num_hops", 5)

        start_nodes = torch.randint(0, self.graph.num_nodes, (n_subgraphs,))
        self.data = [
            self.create_subgraph(start_node, num_hops=num_hops)
            for start_node in start_nodes
        ]
        return self.data

    def create_subgraph(self, start_node, num_hops=5):
        """
        Create a subgraph around a starting node.

        The subgraph contains the nodes within ``num_hops`` hops from the
        starting node.

        :param start_node: The index of the starting node. Tensor inputs must
            contain a single integer value.
        :type start_node: int | torch.Tensor
        :param int num_hops: The number of hops around the starting node.
            Default is ``5``.
        :return: The subgraph centered on the starting node.
        :rtype: Graph
        """
        return self.graph.create_subgraph(start_node, num_hops=num_hops)

    def __len__(self):
        """
        Return the number of stored graph batches.

        :return: The number of subgraphs in ``self.data``.
        :rtype: int
        :raises AttributeError: If :meth:`store_data` has not been called.
        """
        return len(self.data)

    def materialize(self, id, device=None):
        """
        Retrieve a stored graph batch and optionally move it to a device.

        Negative indices follow Python list indexing conventions. Device
        transfer acts on the stored graph rather than creating a copy.

        :param id: The index of the graph batch. Tensor inputs must contain
            a single integer value.
        :type id: int | torch.Tensor
        :param device: The device to move the graph to. If ``None``, no
            device transfer is performed. Default is ``None``.
        :type device: str | torch.device | None
        :return: The selected graph batch.
        :rtype: Graph
        :raises AttributeError: If :meth:`store_data` has not been called.
        :raises IndexError: If the batch index is out of range.
        """
        batch = self.data[int(id)]
        return batch.to(device) if device is not None else batch

    def __getitem__(self, id):
        """
        Retrieve a stored graph batch without changing its device.

        Negative indices follow Python list indexing conventions.

        :param id: The index of the graph batch. Tensor inputs must contain
            a single integer value.
        :type id: int | torch.Tensor
        :return: The selected graph batch.
        :rtype: Graph
        :raises AttributeError: If :meth:`store_data` has not been called.
        :raises IndexError: If the batch index is out of range.
        """
        return self.materialize(id)
